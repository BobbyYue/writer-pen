#!/usr/bin/env python3
"""Render plain literary manuscripts without rewriting text or paragraphs."""
from __future__ import annotations

import argparse
import hashlib
from html import escape
import json
from pathlib import Path
import re
import sys

TEMPLATE = Path(__file__).resolve().parents[1] / 'assets/html/literary-template.html'
MARKER = '<!-- Generated by Writer Pen; HTML mechanics adapted from Reader\'s Seat -->'


def manuscript(path, untitled=False):
    raw = Path(path).read_text(encoding='utf-8').replace('\r\n', '\n').rstrip('\n')
    if untitled:
        if not raw.strip():
            raise ValueError('Manuscript body is empty')
        return {'title': '', 'paragraphs': raw.split('\n\n'), 'text': raw}
    title, separator, body = raw.partition('\n\n')
    if not separator or not title.strip() or '\n' in title or not body.strip():
        raise ValueError('Use a one-line plain title, a blank line, then the manuscript body.')
    if title.startswith('#'):
        raise ValueError('Input is plain text, not Markdown. Put the reviewed title on line 1 without #.')
    paragraphs = body.split('\n\n')
    return {'title': title, 'paragraphs': paragraphs, 'text': raw}


def render(paths, output, language='zh-CN', collection_title=None, draft_notice=None, untitled=False):
    if not re.fullmatch(r'[A-Za-z]{2,3}(?:-[A-Za-z0-9]{2,8})*', language):
        raise ValueError('Invalid language tag')
    works = [manuscript(path, untitled) for path in paths]
    if not works:
        raise ValueError('At least one manuscript is required')
    if len(works) > 1 and not (collection_title and collection_title.strip()):
        raise ValueError('Provide --collection-title for multiple manuscripts')
    title = collection_title if len(works) > 1 else (works[0]['title'] or '文学作品')
    content = []
    if draft_notice:
        content.append('<p class="draft-notice">' + escape(draft_notice) + '</p>')
    if len(works) > 1:
        links = ''.join(f'<li><a href="#work-{i}">{escape(work["title"] or str(i))}</a></li>'
                        for i, work in enumerate(works, 1))
        content.append(f'<header class="collection"><h1>{escape(title)}</h1>'
                       f'<nav aria-label="篇目"><ol>{links}</ol></nav></header>')
    heading = 'h1' if len(works) == 1 else 'h2'
    for i, work in enumerate(works, 1):
        paragraphs = ''.join('<p>' + escape(p) + '</p>' for p in work['paragraphs'])
        header = (f'<header><{heading} data-writer-title>{escape(work["title"])}</{heading}></header>'
                  if work['title'] else '')
        content.append(f'<article id="work-{i}" data-writer-work="{i}">'
                       f'{header}'
                       f'<div class="prose" data-writer-body>{paragraphs}</div></article>')
    replacements = {'{{LANG}}': language, '{{TITLE}}': escape(title), '{{CONTENT}}': '\n'.join(content)}
    html = re.sub(r'\{\{(?:LANG|TITLE|CONTENT)\}\}', lambda m: replacements[m.group()],
                  TEMPLATE.read_text(encoding='utf-8'))
    path = Path(output)
    if path.suffix.lower() != '.html':
        raise ValueError('Output must be an .html file')
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open('x', encoding='utf-8') as handle:
        handle.write(html)
    return {'status': 'rendered-not-reviewed', 'output': str(path.resolve()),
            'html_sha256': hashlib.sha256(path.read_bytes()).hexdigest(), 'works': len(works)}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--text', type=Path, action='append', required=True)
    parser.add_argument('--output', type=Path, required=True)
    parser.add_argument('--lang', default='zh-CN')
    parser.add_argument('--collection-title')
    parser.add_argument('--draft-notice')
    parser.add_argument('--untitled', action='store_true', help='Inputs contain body only; do not add a visible title')
    args = parser.parse_args()
    try:
        result = render(args.text, args.output, args.lang, args.collection_title, args.draft_notice, args.untitled)
    except (OSError, ValueError) as error:
        print(json.dumps({'status': 'error', 'message': str(error)}, ensure_ascii=False), file=sys.stderr)
        return 1
    print(json.dumps(result, ensure_ascii=False, indent=2))
    return 0


if __name__ == '__main__':
    sys.exit(main())
